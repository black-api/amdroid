#!/usr/bin/env python3
"""Regenerate engine/src/tts_tables.h from the Python front end (run from the repo root).

    python3 engine/tools/gen_tts_tables.py

The C voice front end keeps its constant tables (closed-class tags, abbreviations,
number words, the symbol -> model-id map) in a generated header so they cannot
drift from thimble/tts/g2p/english.py and thimble/tts/frontend.py.
"""
import sys
import unicodedata
from pathlib import Path

root = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(root))
from thimble.tts.frontend import DEFAULT_VOCABULARY  # noqa: E402
from thimble.tts.g2p import english as E  # noqa: E402
from thimble.tts.pack import SYMBOLS  # noqa: E402


def code(ch):
    return ord(ch) if ord(ch) < 128 else 0x80 + SYMBOLS.index(ch)


def cstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


fold = []
for cp in range(0xC0, 0x180):
    base = "".join(c for c in unicodedata.normalize("NFD", chr(cp)) if not unicodedata.combining(c))
    fold.append(base if len(base) == 1 and base.isascii() and base.isalpha() else "\0")

vocab = [-1] * 256
for ch, i in DEFAULT_VOCABULARY.items():
    if len(ch) == 1:
        vocab[code(ch)] = i

out = ["/* GENERATED by engine/tools/gen_tts_tables.py from thimble/tts/g2p/english.py - do not edit. */"]
out.append("static const char TTS_LATIN_FOLD[] = {" + ",".join(str(ord(c)) for c in fold) + "};  /* U+00C0..U+017F -> ASCII letter or 0 */")
out.append("static const short TTS_VOCAB_ID[256] = {" + ",".join(map(str, vocab)) + "};")
out.append("typedef struct { const char *word, *tag; } tts_kv;")
out.append("static const tts_kv TTS_CLOSED_CLASS[] = {")
out += ["    {%s, %s}," % (cstr(w), cstr(t)) for w, t in E._CLOSED_CLASS.items()]
out.append("};")
out.append("static const char *const TTS_ABBREVIATIONS[] = {")
out += ["    %s," % cstr(w) for w in sorted(E._ABBREVIATIONS)]
out.append("};")
for name, seq in (("ONES", E._ONES), ("TENS", E._TENS), ("SCALES", E._SCALES)):
    out.append("static const char *const TTS_%s[] = {%s};" % (name, ",".join(cstr(w) for w in seq)))
out.append("/* punctuation character (one-byte code) -> Penn tag */")
out.append("static const tts_kv TTS_PUNCT_TAG[] = {")
out += ['    {"\\x%02x", %s},' % (code(ch), cstr(t)) for ch, t in E._PUNCT_TAG_BY_CHAR.items()]
out.append("};")
(root / "engine/src/tts_tables.h").write_text("\n".join(out) + "\n", encoding="utf-8")
print("wrote engine/src/tts_tables.h")
